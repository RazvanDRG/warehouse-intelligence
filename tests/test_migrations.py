"""The Alembic migrations go up, down and up again on the local test database (T-003 AC-1, T-004 AC-1)."""

import asyncio

from alembic import command
from sqlalchemy import BigInteger, Integer, LargeBinary, Text, inspect
from sqlalchemy.ext.asyncio import create_async_engine

from tests.dbsupport import alembic_config, database_url_or_skip


async def table_info(url: str, table: str) -> dict:
    """Columns (with a primary_key flag) and unique constraints of a table; empty when it does not exist."""
    engine = create_async_engine(url)
    try:
        async with engine.connect() as conn:

            def read(sync_conn):
                inspector = inspect(sync_conn)
                if not inspector.has_table(table):
                    return {}
                pk = inspector.get_pk_constraint(table)["constrained_columns"]
                return {
                    "columns": {
                        c["name"]: {**c, "primary_key": c["name"] in pk} for c in inspector.get_columns(table)
                    },
                    "unique": [u["column_names"] for u in inspector.get_unique_constraints(table)],
                }

            return await conn.run_sync(read)
    finally:
        await engine.dispose()


def info(url: str, table: str) -> dict:
    return asyncio.run(table_info(url, table))


def check_processed_events(url: str) -> None:
    columns = info(url, "processed_events")["columns"]
    assert list(columns) == ["event_id", "topic", "partition", "offset", "processed_at"]
    assert [name for name, c in columns.items() if c["primary_key"]] == ["event_id"]
    assert isinstance(columns["event_id"]["type"], Text)
    assert isinstance(columns["topic"]["type"], Text)
    assert isinstance(columns["partition"]["type"], Integer)
    assert isinstance(columns["offset"]["type"], BigInteger)
    assert all(not c["nullable"] for c in columns.values())
    assert columns["processed_at"]["default"] is not None
    assert columns["processed_at"]["type"].timezone is True


def check_dead_letters(url: str) -> None:
    table = info(url, "dead_letters")
    columns = table["columns"]
    assert list(columns) == ["id", "topic", "partition", "offset", "payload", "error", "created_at"]
    assert [name for name, c in columns.items() if c["primary_key"]] == ["id"]
    assert isinstance(columns["id"]["type"], BigInteger)
    assert columns["id"].get("identity") is not None, "id must be generated by the database"
    assert isinstance(columns["topic"]["type"], Text)
    assert isinstance(columns["partition"]["type"], Integer)
    assert isinstance(columns["offset"]["type"], BigInteger)
    assert isinstance(columns["payload"]["type"], LargeBinary)
    assert isinstance(columns["error"]["type"], Text)
    assert [name for name, c in columns.items() if c["nullable"]] == ["payload"]
    assert columns["created_at"]["default"] is not None
    assert columns["created_at"]["type"].timezone is True
    assert table["unique"] == [["topic", "partition", "offset"]]


def test_upgrade_downgrade_upgrade():
    url = database_url_or_skip()
    config = alembic_config(url)

    command.upgrade(config, "head")
    check_dead_letters(url)

    # One step down removes only dead_letters.
    command.downgrade(config, "0001")
    assert info(url, "dead_letters") == {}, "downgrade 0001 left dead_letters behind"
    check_processed_events(url)

    command.downgrade(config, "base")
    assert info(url, "processed_events") == {}, "downgrade left processed_events behind"

    command.upgrade(config, "head")
    check_processed_events(url)
    check_dead_letters(url)
